"""Agent-loop tests for the SPEC path's LIVE-weights simulator.

Selected by ``+colbench.sim_live=True``.

Sibling of ``test_agent_loop_live_sim.py`` (the GT path's live arm). The arm
under test keeps ONE copy of the weights for the whole run: the user turn is
generated by ``server_manager.generate`` (the training rollout engine) instead
of an HTTP call to a frozen sim server. Unlike the GT path -- whose env grew an
async ``asim_backend`` twin -- the spec path swaps the env's SYNC
``sim_backend``, precisely so the spec termination state machine
(``generate_user_turn``: two rejection grounds on one try budget, the
premature-[TERMINATE] guard, the per-draw census) is NOT duplicated. That makes
the load-bearing assertions here:

  * the sim's prompt is BYTE-IDENTICAL to the frozen path's (the ENV still
    builds it, per arm), so the two arms differ only in which weights answer;
  * the env's rejection sampler still runs -- resample, exhaustion, census
    counters -- through the sync bridge, i.e. the swap really is only "who
    answers";
  * the sim's generated TOKENS never enter the solver trajectory (only the reply
    text does, at mask=0), so the leak invariant and the mask bookkeeping are
    unchanged;
  * the sim call uses a FRESH request_id (not the solver's shared KV-prefix
    session);
  * ``min/max_global_steps`` reflect the SOLVER turns only.

CONTAINER-ONLY in spirit (imports verl.experimental.agent_loop), but the
conftest StrEnum backport + in-process grading let it run in the py3.10 conda
env too: CODECONTEST_ALLOW_INPROCESS=1 python -m pytest
colbench/tests/test_agent_loop_live_sim_spec.py -v
"""

