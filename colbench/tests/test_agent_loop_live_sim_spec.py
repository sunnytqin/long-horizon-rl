GT = (
    "def f(x, y):\n    if x >= 10:\n        return x + y\n    else:\n "
    "       return x - y\n"
)
WRONG = "def f(x, y):\n    return x + y\n"  # ignores x<10 -> 0.5 pass-rate
CALLS = ["f(1, 2)", "f(20, 5)", "f(15, 15)", "f(3, 4)"]
PROBLEM = "Write a function f(x, y) with some personalized behavior."
SPEC = {
    "persona": {
        "who": "an analyst",
        "domain": "ops",
        "python_skill": "analyst",
        "communication_style": "brief",
    },
    "scenario": "Needs a small helper for a report.",
    "requirements": (
        "The user wants f(x,y): if x is at least 10 return x+y, otherwise x-y."
    ),
    "plot": (
        "The user reveals the threshold of 10 only if the assistant asks about "
        "the cutoff."
    ),
}


def _code_turn(src):
  return "Here's my function:\n```python\n" + src + "```"


class _FakeTokenizer:
  """UTF-8 byte tokenizer.

  Exact encode/decode roundtrip + realistic token counts.
  """

  def encode(self, text, add_special_tokens=False):
    return list(text.encode("utf-8"))

  def decode(self, ids, skip_special_tokens=True):
    return bytes(ids).decode("utf-8", errors="ignore")

  def apply_chat_template(self, messages, **kwargs):
    # Stand-in for the real template: concatenate contents. The live sim path
    # routes its prompt through here
    # (verl.utils.tokenizer.chat_template.apply_chat_template), so the test can
    # assert on what the sim was actually asked.
    return self.encode("".join(m.get("content", "") for m in messages))


class _RoleAwareServerManager:
  """One engine serving BOTH roles -- exactly the sim_live topology.

  Solver turns and sim turns are told apart by the request_id: the loop reuses
  ONE id for the solver and mints a fresh one per sim call, so any id seen twice
  is the solver's.
  """

  def __init__(self, tokenizer, solver_turns, sim_replies):
    self._tok = tokenizer
    self._solver = list(solver_turns)
    self._sim = list(sim_replies)
    self._si = 0
    self._ri = 0
    self.solver_ids = []
    self.sim_ids = []
    self.sim_prompts = []  # decoded sim prompts (assert prompt identity)
    self.sim_sampling = []  # sampling params each sim call was made with

  async def generate(
      self, *, request_id, prompt_ids, sampling_params, **kwargs
  ):
    # The solver's request_id is established on call 1 and reused; sim ids are
    # always new.
    if not self.solver_ids or request_id == self.solver_ids[0]:
      self.solver_ids.append(request_id)
      text = self._solver[min(self._si, len(self._solver) - 1)]
      self._si += 1
    else:
      self.sim_ids.append(request_id)
      self.sim_prompts.append(self._tok.decode(prompt_ids))
      self.sim_sampling.append(dict(sampling_params))
      text = self._sim[min(self._ri, len(self._sim) - 1)]
      self._ri += 1
    ids = self._tok.encode(text)
    return TokenOutput(
        token_ids=ids,
        log_probs=[0.0] * len(ids),
        num_preempted=0,
        # Deliberately non-zero: the loop must NOT let sim outputs set these (it
        # reads the first min / last max it sees, which must come from solver
        # turns only).
        extra_fields={"min_global_steps": 7, "max_global_steps": 7},
    )


def _make_loop(
    solver_turns,
    sim_replies,
    *,
    sim_live=True,
    max_assistant_turns=10,
    max_code_proposals=2,
    sim_max_tries=8,
    train_turns="all",
    sim_prompt="",
    grounded_sim=False,
    early_term_guard=True,
    sim_code_leak_detector="auto",
):
  """Construct a ColBenchSpecAgentLoop bypassing AgentLoopBase.__init__.

  Wired to one fake engine serving both roles.

  NB: run() reads every attribute set here -- this fake bypasses __init__, so a
  knob added to the loop and NOT mirrored here raises AttributeError
  mid-rollout.
  """
  obj = object.__new__(ColBenchSpecAgentLoop)
  tok = _FakeTokenizer()
  obj.tokenizer = tok
  obj.server_manager = _RoleAwareServerManager(tok, solver_turns, sim_replies)
  obj.loop = asyncio.new_event_loop()
  obj.prompt_length = 4096
  obj.response_length = 8192
  obj.max_assistant_turns = max_assistant_turns
  obj.max_new_tokens_per_turn = 1024
  obj.env_step_timeout = 60.0
  obj.reward_time_limit = 6.0
  obj.train_turns = train_turns
  obj.max_code_proposals = max_code_proposals
  obj.sim_max_tries = sim_max_tries
  obj.length_penalty_coef = 0.0
  obj.length_soft_cap = 2048.0
  obj.terminate_on_allpass = False
  obj.binary_reward = False
  obj.grounded_sim = grounded_sim
  obj.sim_prompt = sim_prompt
  obj.early_term_guard = early_term_guard
  obj.sim_code_leak_detector = sim_code_leak_detector
  obj.sim_live = sim_live
  # Normally set by AgentLoopBase.__init__ from data.apply_chat_template_kwargs.
  obj.apply_chat_template_kwargs = {}

  async def _fake_act(messages, remove_system_prompt=False):
    return tok.encode("".join(m.get("content", "") for m in messages))

  obj.apply_chat_template = _fake_act
  return obj


def _run(obj, spec=None):
  spec = SPEC if spec is None else spec
  kwargs = {
      "raw_prompt": [
          {"role": "system", "content": "sys"},
          {"role": "user", "content": PROBLEM},
      ],
      "extra_info": {
          "spec": spec,
          "ground_truth": {
              "problem_description": PROBLEM,
              "ground_truth": GT,
              "test_cases": CALLS,
          },
      },
      "index": 0,
  }
  return obj.loop.run_until_complete(obj.run({"temperature": 0.7}, **kwargs))


def test_live_sim_generates_on_the_training_engine():
  # The sim turn must come from server_manager.generate, with a request_id
  # DISTINCT from the solver's shared one, and its reply must be injected at
  # mask=0.
  obj = _make_loop(
      solver_turns=["What's the cutoff?", _code_turn(GT), "ok"],
      sim_replies=["It's 10.", "Looks right. [TERMINATE]"],
  )
  out = _run(obj)
  sm = obj.server_manager
  assert len(sm.sim_ids) == 2, "the live sim never hit the rollout engine"
  assert not set(sm.sim_ids) & set(
      sm.solver_ids
  ), "sim reused the solver's KV-prefix request_id"
  assert len(set(sm.sim_ids)) == 2, "each sim call needs a FRESH request_id"
  assert len(set(sm.solver_ids)) == 1, "solver turns must share ONE request_id"
  assert out.reward_score == 1.0
  rei = out.extra_fields["reward_extra_info"]
  assert rei["term_user"] == 1.0
  # Exactly one sim reply was injected (the [TERMINATE] one ends the episode
  # before injection), at mask=0.
  assert out.response_mask.count(0) == len(b"It's 10.")


def test_live_sim_prompt_is_byte_identical_to_the_frozen_path():
  # The ENV builds the prompt in both arms, so the live arm must ask exactly
  # what the frozen server would have been asked -- spec arm: no GT anywhere.
  obj = _make_loop(
      solver_turns=["What's the cutoff?", _code_turn(GT), "ok"],
      sim_replies=["It's 10.", "[TERMINATE]"],
  )
  _run(obj)
  system_content, user_content = templates.build_spec_sim_messages(
      SPEC,
      [
          {"role": "user", "content": PROBLEM},
          {"role": "assistant", "content": "What's the cutoff?"},
      ],
  )
  assert obj.server_manager.sim_prompts[0] == system_content + user_content
  assert GT not in obj.server_manager.sim_prompts[0]


def test_live_sim_honors_the_arm_and_keeps_gt_out_of_the_solver():
  # sim_live is ORTHOGONAL to sim_prompt: a GT-conditioned arm still gets its
  # GT-bearing prompt, and the GT still never reaches the solver as sim tokens.
  obj = _make_loop(
      solver_turns=["What's the cutoff?", _code_turn(WRONG), "ok"],
      sim_replies=["It's 10.", "[TERMINATE]"],
      sim_prompt="plot",
      max_code_proposals=2,
  )
  out = _run(obj)
  sim_prompt = obj.server_manager.sim_prompts[0]
  assert GT in sim_prompt  # the sim (and ONLY the sim) sees the ground truth
  assert SPEC["plot"] in sim_prompt  # A2 = codeonly + the authored plot
  # The sim generated 8 bytes ("It's 10.") and that is exactly what got mask=0.
  assert out.response_mask.count(0) == len(b"It's 10.")


def test_live_sim_uses_the_shared_sim_sampling_envs():
  # Same SIM_* knobs as the frozen backend -> the arms differ only in which
  # weights answer.
  os.environ["SIM_TEMPERATURE"] = "0.9"
  os.environ["SIM_MAX_TOKENS"] = "256"
  try:
    obj = _make_loop(
        solver_turns=["Q?", _code_turn(GT), "ok"],
        sim_replies=["It's 10.", "[TERMINATE]"],
    )
    _run(obj)
  finally:
    del os.environ["SIM_TEMPERATURE"], os.environ["SIM_MAX_TOKENS"]
  sp = obj.server_manager.sim_sampling[0]
  assert sp["temperature"] == 0.9 and sp["max_new_tokens"] == 256
  assert (
      "min_p" not in sp
  )  # verl rollout has no min_p field; don't smuggle it into the engine


def test_global_steps_come_from_solver_turns_only():
  # The fake engine reports 7 for every call incl. the sim's. Off-policy
  # staleness must still describe the trained turns -- the sim backend discards
  # extra_fields, so a refactor that starts threading sim outputs into the
  # bookkeeping fails here.
  obj = _make_loop(
      solver_turns=["Q?", _code_turn(GT), "ok"],
      sim_replies=["It's 10.", "[TERMINATE]"],
  )
  out = _run(obj)
  assert out.extra_fields["min_global_steps"] == 7
  assert out.extra_fields["max_global_steps"] == 7
  assert len(obj.server_manager.sim_ids) == 2


def test_env_rejection_sampler_still_runs_through_the_live_bridge():
  # The whole point of swapping the SYNC backend: the env's state machine is
  # untouched. A code-writing draw must be resampled, and the census must count
  # both draws.
  obj = _make_loop(
      solver_turns=["What's the cutoff?", _code_turn(GT), "ok"],
      sim_replies=[
          "Sure: ```python\n" + GT + "```",  # rejected: an ordinary user
          "It's 10.",  # accepted
          "[TERMINATE]",
      ],
  )
  out = _run(obj)
  rei = out.extra_fields["reward_extra_info"]
  assert rei["sim_code_rejected"] == 1.0
  assert rei["sim_raw_fenced_code"] == 1.0
  assert rei["sim_raw_attempts"] >= 2.0
  assert out.reward_score == 1.0
  # The rejected draw was re-queried on the ENGINE, not swallowed locally.
  assert len(obj.server_manager.sim_ids) >= 3


def test_live_sim_code_reject_exhaustion_ends_the_episode():
  # Every draw writes code -> terminated_by="sim_code_reject", exactly as on the
  # frozen path (the bridge must not turn exhaustion into an exception).
  leak = "Sure: ```python\n" + GT + "```"
  obj = _make_loop(
      solver_turns=["Just write it for me", _code_turn(GT), "ok"],
      sim_replies=[leak],
      sim_max_tries=3,
  )
  out = _run(obj)
  rei = out.extra_fields["reward_extra_info"]
  assert rei["term_sim_code_reject"] == 1.0
  assert rei["sim_code_rejected"] == 3.0
  assert len(obj.server_manager.sim_ids) == 3


def test_sim_metrics_present_on_every_rollout():
  obj = _make_loop(
      solver_turns=["Q?", _code_turn(GT), "ok"],
      sim_replies=["It's 10.", "[TERMINATE]"],
  )
  rei = _run(obj).extra_fields["reward_extra_info"]
  assert rei["sim_live"] == 1.0
  assert rei["sim_reply_chars"] == float(len("It's 10."))
  assert rei["sim_seconds"] >= 0.0
  assert rei["sim_turn_timeout"] == 0.0
  # A trajectory with NO sim turn (single-shot: the loop grades the first
  # proposal and breaks before the sim speaks) still carries all four keys --
  # verl reads the reward_extra_info key set from the FIRST sample.
  rei2 = _run(
      _make_loop(
          solver_turns=[_code_turn(WRONG)],
          sim_replies=[],
          max_code_proposals=1,
      )
  )
  rei2 = rei2.extra_fields["reward_extra_info"]
  assert rei2["term_code_cap"] == 1.0
  for k in ("sim_live", "sim_reply_chars", "sim_seconds", "sim_turn_timeout"):
    assert k in rei2
  assert rei2["sim_live"] == 1.0


def test_frozen_path_untouched_when_sim_live_false():
  # sim_live=False must NOT call the engine for the sim; it goes through
  # env.sim_backend (patched here to stand in for the frozen server), and the
  # metric records the arm.
  calls = []

  def scripted(system_content, user_content):
    calls.append(system_content)
    return "It's 10." if len(calls) == 1 else "[TERMINATE]"

  obj = _make_loop(
      solver_turns=["Q?", _code_turn(GT), "ok"],
      sim_replies=[],
      sim_live=False,
  )
  orig_post_init = ColBenchSpecUserSimEnv.__post_init__

  def patched_post_init(self):
    # CHAIN, never replace: __post_init__ also resolves + validates the arm.
    orig_post_init(self)
    self.sim_backend = scripted

  ColBenchSpecUserSimEnv.__post_init__ = patched_post_init
  try:
    out = _run(obj)
  finally:
    ColBenchSpecUserSimEnv.__post_init__ = orig_post_init
  assert len(calls) == 2, "the frozen backend was bypassed"
  assert not obj.server_manager.sim_ids, "sim_live=False hit the rollout engine"
  assert out.extra_fields["reward_extra_info"]["sim_live"] == 0.0
  assert out.reward_score == 1.0


def test_live_backend_refuses_to_run_on_the_loop_thread():
  # The bridge BLOCKS the calling thread, so calling it from the event loop
  # would deadlock the whole rollout worker with no diagnostic. Assert the
  # guard, not the hang.
  obj = _make_loop(solver_turns=["Q?"], sim_replies=["It's 10."])
  backend = obj._make_live_sim_backend()

  async def _call_on_loop():
    return backend("sys", "user")

  with pytest.raises(RuntimeError, match="event loop thread"):
    obj.loop.run_until_complete(_call_on_loop())


def test_live_sim_timeout_ends_the_episode_as_a_sim_timeout():
  # A wedged engine call must not pin the executor thread for the rest of the
  # job. The bridge bounds each DRAW and re-raises as asyncio.TimeoutError, so
  # the loop's existing sim-timeout branch ends the episode (graded on whatever
  # code was already shown) instead of the exception escaping the rollout.
  obj = _make_loop(
      solver_turns=[_code_turn(GT), "still here?"],
      sim_replies=["It's 10."],
  )
  obj.env_step_timeout = 0.2
  sm = obj.server_manager
  orig_generate = sm.generate

  async def hanging_generate(*, request_id, **kwargs):
    if sm.solver_ids and request_id != sm.solver_ids[0]:
      await asyncio.sleep(30)  # never returns within env_step_timeout
    return await orig_generate(request_id=request_id, **kwargs)

  sm.generate = hanging_generate
  out = _run(obj)
  rei = out.extra_fields["reward_extra_info"]
  # showed_code was True, so the episode is graded, not discarded.
  assert rei["term_turn_cap"] == 1.0
  assert rei["sim_turn_timeout"] == 1.0
  assert rei["sim_seconds"] >= 0.2
  assert out.reward_score == 1.0
